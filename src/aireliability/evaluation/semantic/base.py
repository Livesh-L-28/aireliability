"""Provider abstraction and protocols for semantic evaluation."""

from datetime import UTC, datetime
from typing import Any, Protocol, runtime_checkable

from pydantic import BaseModel, ConfigDict, Field, model_validator


class JudgeResult(BaseModel):
    """Structured result returned by a semantic judge provider."""

    model_config = ConfigDict(frozen=True)

    passed: bool
    score: float = Field(ge=0.0, le=1.0)
    reasoning: str = ""
    evidence: dict[str, Any] = Field(default_factory=dict)
    criteria_results: dict[str, bool] = Field(default_factory=dict)
    confidence: float | None = Field(default=None, ge=0.0, le=1.0)
    provider: str = ""
    model: str = ""
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))
    metadata: dict[str, Any] = Field(default_factory=dict)

    @model_validator(mode="after")
    def validate_confidence_if_missing(self) -> "JudgeResult":
        """Default confidence to score if not explicitly set by the judge."""
        if self.confidence is None:
            object.__setattr__(self, "confidence", round(self.score, 3))
        return self


@runtime_checkable
class SemanticJudge(Protocol):
    """Provider-independent protocol for an LLM or semantic judge.

    Isolates external models (OpenAI, Anthropic, Gemini, local SLMs) from the
    core evaluation framework.
    """

    name: str

    def judge(
        self,
        prompt: str,
        output: str,
        reference: str | None = None,
        criteria: list[str] | None = None,
        context: dict[str, Any] | None = None,
    ) -> JudgeResult:
        """Evaluate agent output against prompt, reference, criteria, and context.

        Args:
            prompt: The original user request or task input.
            output: The output string generated by the agent.
            reference: Optional expected reference answer.
            criteria: Optional list of explicit evaluation criteria.
            context: Optional grounding context (e.g. retrieved documents).

        Returns:
            A structured JudgeResult containing score, pass/fail status,
            reasoning, and evidence.
        """
